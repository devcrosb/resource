"""A standalone renderer for a documented subset of MediaWiki markup.

Python 3.10+. Standard library only; no regex-based wiki-markup parser,
third-party packages, network requests, template expansion, or raw-HTML mode.
Public entry points: HTML(), Markdown(), and Headers().
"""
from __future__ import annotations

from collections.abc import Callable
from html import escape, unescape
from html.parser import HTMLParser
from urllib.parse import quote, urlsplit

__all__ = ["HTML", "Markdown", "Headers"]

_ASCII_LOWER = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")
_LIST_TAGS = {"*": ("ul", "li"), "#": ("ol", "li"), ";": ("dl", "dt"), ":": ("dl", "dd")}



def _entities(text: str) -> str:
    """Decode only semicolon-terminated entities, not things like '&notable'."""
    out: list[str] = []
    start = 0
    while True:
        i = text.find("&", start)
        if i < 0:
            out.append(text[start:])
            return "".join(out)
        out.append(text[start:i])
        j = text.find(";", i + 1, i + 40)
        if j < 0 or any(c.isspace() or c in "<&" for c in text[i + 1:j]):
            out.append("&")
            start = i + 1
        else:
            out.append(unescape(text[i:j + 1]))
            start = j + 1


def _text(text: str) -> str:
    return escape(_entities(text), quote=False)


def _safe_url(url: str) -> str | None:
    """Validate a literal URL, never HTML. Do not dereference it."""
    url = url.strip()
    if not url or any(c.isspace() or ord(c) < 32 or ord(c) == 127 or c in "\\<>\"'" for c in url):
        return None
    if url.startswith("//"):
        return None
    try:
        parts = urlsplit(url)
        if parts.scheme.lower() in {"http", "https"}:
            if not parts.hostname:
                return None
            _ = parts.port  # Reject invalid/out-of-range ports too.
            return url
        if parts.scheme.lower() == "mailto":
            return url if parts.path and not parts.netloc else None
        if not parts.scheme and not parts.netloc:
            return url
    except ValueError:
        pass
    return None


class _PlainText(HTMLParser):
    """Extract visible text from HTML generated by this renderer only."""
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []

    def handle_data(self, data: str) -> None:
        self.parts.append(data)

    def handle_starttag(self, tag: str, attrs: list) -> None:
        if tag == "br":
            self.parts.append(" ")


def _plain_html(html: str) -> str:
    parser = _PlainText()
    parser.feed(html)
    parser.close()
    return "".join(parser.parts)


def _anchor(text: str) -> str:
    return "wiki-" + ("_".join(text.split()) or "section")


def _split_outside(text: str, delimiter: str, maxsplit: int = -1) -> list[str]:
    """Split outside brackets, protected spans, and quoted attribute values."""
    parts: list[str] = []
    depth = 0
    in_quote = ""
    i = start = 0
    previous = ""
    while i < len(text):
        c = text[i]
        if c == "\x00":
            end = text.find("\x00", i + 1)
            i = end + 1 if end >= 0 else i + 1
            continue
        if in_quote:
            if c == in_quote:
                in_quote = ""
        elif c in "\"'" and previous == "=":
            in_quote = c
        elif c == "[":
            depth += 1
        elif c == "]" and depth:
            depth -= 1
        elif depth == 0 and text.startswith(delimiter, i):
            parts.append(text[start:i])
            i += len(delimiter)
            start = i
            if 0 <= maxsplit == len(parts):
                break
            continue
        if not c.isspace():
            previous = c
        i += 1
    parts.append(text[start:])
    return parts


def _attributes(text: str, cell: bool = False) -> str:
    """Emit a small attribute allowlist. CSS, ids, and events are not copied."""
    values: dict[str, str] = {}
    i = 0
    while i < len(text):
        while i < len(text) and text[i].isspace():
            i += 1
        start = i
        while i < len(text) and (text[i].isascii() and (text[i].isalnum() or text[i] in "_-")):
            i += 1
        name = text[start:i].lower()
        if not name:
            i += 1
            continue
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text) or text[i] != "=":
            continue
        i += 1
        while i < len(text) and text[i].isspace():
            i += 1
        if i < len(text) and text[i] in "\"'":
            delimiter = text[i]
            i += 1
            start = i
            while i < len(text) and text[i] != delimiter:
                i += 1
            value = text[start:i]
            i += 1
        else:
            start = i
            while i < len(text) and not text[i].isspace():
                i += 1
            value = text[start:i]
        value = _entities(value)
        if "\x00" in value:
            continue
        if name in {"class", "title"}:
            values[name] = value
        elif cell and name in {"rowspan", "colspan"}:
            if value.isascii() and value.isdigit() and len(value) <= 4 and 1 <= int(value) <= 1000:
                values[name] = str(int(value))
        elif cell and name == "scope" and value in {"row", "col", "rowgroup", "colgroup"}:
            values[name] = value
    return "".join(f' {name}="{escape(value, quote=True)}"' for name, value in values.items())


class _Renderer:
    def __init__(self, wiki_base: str, link_resolver: Callable[[str], str | None] | None,
                 max_list_depth: int) -> None:
        self.wiki_base = wiki_base
        self.link_resolver = link_resolver
        self.max_list_depth = max_list_depth
        self.spans: list[tuple[str, str]] = []
        self.headings: list[tuple[int, str, str]] = []
        self.ids: set[str] = set()
        self.id_counts: dict[str, int] = {}
        self.external_number = 0

    def protect(self, text: str) -> str:
        """Tokenize literal regions before any line/block or inline processing."""
        # Literal NULs become replacement characters; only our tokens contain NUL.
        text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "\ufffd")
        lower = text.translate(_ASCII_LOWER)  # Same offsets, including non-ASCII text.
        out: list[str] = []
        i = start = 0
        while i < len(text):
            kind = ""
            body = ""
            end = i
            if text.startswith("<!--", i):
                close = text.find("-->", i + 4)
                if close < 0:
                    kind, body, end = "literal", text[i:], len(text)
                else:
                    out.append(text[start:i])
                    i = start = close + 3
                    continue
            elif text.startswith("{{", i):
                depth, end = 1, i + 2
                while end < len(text) and depth:
                    if text.startswith("{{", end):
                        depth += 1
                        end += 2
                    elif text.startswith("}}", end):
                        depth -= 1
                        end += 2
                    else:
                        end += 1
                kind, body = "literal", text[i:end]
            elif text[i] == "<":
                for tag in ("nowiki", "code", "pre"):
                    opening = f"<{tag}>"
                    if lower.startswith(opening, i):
                        close = lower.find(f"</{tag}>", i + len(opening))
                        if close < 0:
                            kind, body, end = "literal", text[i:], len(text)
                        else:
                            kind = tag
                            body = text[i + len(opening):close]
                            end = close + len(tag) + 3
                        break
                if not kind:
                    for opening in ("<nowiki/>", "<nowiki />"):
                        if lower.startswith(opening, i):
                            kind, end = "nowiki", i + len(opening)
                            break
            if kind:
                out.append(text[start:i])
                token = f"\x00{len(self.spans)}\x00"
                self.spans.append((kind, body))
                out.append("\n" + token + "\n" if kind == "pre" else token)
                i = start = end
            else:
                i += 1
        out.append(text[start:])
        return "".join(out)

    def source_text(self, text: str) -> str:
        """Expand tokens as text, never by substitution into emitted HTML."""
        out: list[str] = []
        start = 0
        while True:
            i = text.find("\x00", start)
            if i < 0:
                out.append(text[start:])
                return "".join(out)
            j = text.index("\x00", i + 1)
            out.append(text[start:i])
            out.append(self.spans[int(text[i + 1:j])][1])
            start = j + 1

    def page_url(self, target: str) -> str | None:
        if self.link_resolver is not None:
            result = self.link_resolver(target)
            if result is not None and not isinstance(result, str):
                raise TypeError("link_resolver must return str or None")
            return _safe_url(result) if result is not None else None
        page, separator, fragment = target.partition("#")
        url = self.wiki_base + quote(page.replace(" ", "_"), safe="/") if page else ""
        if separator:
            url += "#" + quote(_anchor(fragment), safe="")
        return _safe_url(url)

    @staticmethod
    def bracket_ends(text: str) -> dict[int, tuple[int, int]]:
        """Match bracket pairs once, so unmatched openers do not rescan suffixes."""
        stack: list[tuple[int, int]] = []
        ends: dict[int, tuple[int, int]] = {}
        i = 0
        while i < len(text):
            if text[i] == "\x00":
                i = text.index("\x00", i + 1) + 1
                continue
            if text[i] == "[":
                width = 2 if text.startswith("[[", i) else 1
                stack.append((i, width))
                i += width
                continue
            if text[i] == "]" and stack:
                start, width = stack[-1]
                if width == 1 or text.startswith("]]", i):
                    stack.pop()
                    ends[start] = (i + width, width)
                    i += width
                    continue
            i += 1
        return ends

    def inline(self, text: str, links: bool = True) -> str:
        ends = self.bracket_ends(text) if links and "[" in text else {}
        out: list[str] = []
        styles: list[str] = []
        start = i = 0

        def flush() -> None:
            if start < i:
                out.append(_text(text[start:i]))

        def toggle(tag: str) -> None:
            if tag not in styles:
                out.append(f"<{tag}>")
                styles.append(tag)
                return
            position = styles.index(tag)
            reopen = styles[position + 1:]
            out.extend(f"</{t}>" for t in reversed(styles[position:]))
            del styles[position:]
            for t in reopen:
                out.append(f"<{t}>")
                styles.append(t)

        while i < len(text):
            c = text[i]
            if c == "\x00":
                flush()
                end = text.index("\x00", i + 1)
                kind, body = self.spans[int(text[i + 1:end])]
                literal = escape(body, quote=False) if kind == "literal" else _text(body)
                out.append(f"<code>{literal}</code>" if kind in {"code", "pre"} else literal)
                i = start = end + 1
                continue
            if c == "'" and text.startswith("''", i):
                flush()
                end = i + 2
                while end < len(text) and text[end] == "'":
                    end += 1
                count = end - i
                if count == 4:
                    out.append("'")
                    toggle("b")
                elif count >= 5:
                    out.append("'" * (count - 5))
                    if len(styles) == 2:
                        out.extend(f"</{t}>" for t in reversed(styles))
                        styles.clear()
                    elif styles:
                        old = styles[-1]
                        toggle(old)
                        toggle("i" if old == "b" else "b")
                    else:
                        toggle("b")
                        toggle("i")
                else:
                    toggle("i" if count == 2 else "b")
                i = start = end
                continue
            if c == "\n" and styles:
                flush()
                out.extend(f"</{t}>" for t in reversed(styles))
                styles.clear()
                out.append("\n")
                i += 1
                start = i
                continue
            if c == "<":
                for br in ("<br>", "<br/>", "<br />"):
                    if text[i:i + len(br)].lower() == br:
                        flush()
                        out.append("<br>")
                        i = start = i + len(br)
                        break
                else:
                    i += 1
                    continue
                continue
            if links and i in ends:
                end, width = ends[i]
                body = text[i + width:end - width]
                href = None
                label = ""
                recognized = False
                preserve = False
                if width == 2:
                    target, separator, label = body.partition("|")
                    target = _entities(self.source_text(target)).strip()
                    recognized = bool(target) and "[" not in target and "]" not in target
                    preserve = target.split(":", 1)[0].lower() in {"file", "image", "category"}
                    if recognized and not preserve:
                        href = self.page_url(target.lstrip(":"))
                        # An unlabelled target is plain text, not recursively parsed markup.
                        label_html = self.inline(label, links=False) if separator and label else escape(target, quote=False)
                else:
                    parts = body.split(None, 1)
                    if parts:
                        url = _entities(self.source_text(parts[0]))
                        scheme = url.split(":", 1)[0].lower()
                        recognized = scheme in {"http", "https", "mailto"}
                        if recognized:
                            href = _safe_url(url)
                            if len(parts) == 2:
                                label_html = self.inline(parts[1], links=False)
                            else:
                                self.external_number += 1
                                label_html = f"[{self.external_number}]"
                # Consume even unsupported matched brackets as a unit. This
                # prevents repeated suffix processing on deeply nested input.
                if not recognized and not preserve:
                    flush()
                    if width == 1:
                        out.append("[" + self.inline(body, links=False) + "]")
                    else:
                        out.append(escape(self.source_text(text[i:end]), quote=False))
                    i = start = end
                    continue
                if recognized or preserve:
                    flush()
                    if preserve:
                        out.append(escape(self.source_text(text[i:end]), quote=False))
                    elif href:
                        out.append(f'<a href="{escape(href, quote=True)}">{label_html}</a>')
                    else:
                        out.append(label_html)
                    i = start = end
                    continue
            if links and c in "hH" and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_\"'=/")):
                is_url = text[i:i + 8].lower().startswith(("https://", "http://"))
                if is_url:
                    end = i
                    while end < len(text) and not text[end].isspace() and text[end] not in "<>\"'\x00":
                        end += 1
                    candidate = text[i:end]
                    excess = {")": candidate.count(")") - candidate.count("("),
                              "]": candidate.count("]") - candidate.count("[")}
                    trimmed = len(candidate)
                    while trimmed:
                        last = candidate[trimmed - 1]
                        if last in ".,;:!?":
                            trimmed -= 1
                        elif excess.get(last, 0) > 0:
                            excess[last] -= 1
                            trimmed -= 1
                        else:
                            break
                    candidate = candidate[:trimmed]
                    href = _safe_url(_entities(candidate))
                    if href:
                        flush()
                        out.append(f'<a href="{escape(href, quote=True)}">{_text(candidate)}</a>')
                        i = start = i + len(candidate)
                        continue
                    # Do not retry each apparent URL within a rejected, unbroken
                    # candidate (which would repeatedly scan the same suffix).
                    flush()
                    out.append(_text(text[i:end]))
                    i = start = end
                    continue
            i += 1
        flush()
        out.extend(f"</{tag}>" for tag in reversed(styles))
        return "".join(out)

    def table(self, lines: list[str]) -> str:
        """Flat wiki tables; multiline cell text supports inline formatting."""
        rows: list[str] = []
        cells: list[tuple[str, str, list[str]]] = []
        row_attrs = ""
        caption = ""

        def flush_row() -> None:
            if cells:
                rendered = [f"<{tag}{attrs}>{self.inline(chr(10).join(body).strip())}</{tag}>"
                            for tag, attrs, body in cells]
                rows.append(f"<tr{row_attrs}>" + "".join(rendered) + "</tr>")
                cells.clear()

        def content(text: str, cell: bool = True) -> tuple[str, str]:
            parts = _split_outside(text, "|", 1)
            if len(parts) == 2 and "=" in parts[0]:
                return _attributes(parts[0], cell=cell), parts[1].strip()
            return "", text.strip()

        for line in lines[1:-1]:
            if line.startswith("|-"):
                flush_row()
                row_attrs = _attributes(line[2:])
            elif line.startswith("|+"):
                if caption:
                    return "<pre>" + escape(self.source_text("\n".join(lines)), quote=False) + "</pre>"
                attrs, body = content(line[2:], cell=False)
                caption = f"<caption{attrs}>{self.inline(body)}</caption>"
            elif line.startswith(("|", "!")):
                tag = "th" if line[0] == "!" else "td"
                separator = "!!" if tag == "th" else "||"
                for part in _split_outside(line[1:], separator):
                    attrs, body = content(part)
                    cells.append((tag, attrs, [body]))
            elif cells:
                cells[-1][2].append(line)
            elif line.strip():
                return "<pre>" + escape(self.source_text("\n".join(lines)), quote=False) + "</pre>"
        flush_row()
        attrs = _attributes(lines[0][2:])
        return f"<table{attrs}>\n" + (caption + "\n" if caption else "") + "\n".join(rows) + "\n</table>"

    def blocks(self, text: str) -> str:
        out: list[str] = []
        paragraph: list[str] = []
        lists: list[tuple[str, str]] = []
        lines = text.split("\n")
        i = 0

        def flush_paragraph() -> None:
            if paragraph:
                out.append("<p>" + self.inline("\n".join(paragraph)) + "</p>")
                paragraph.clear()

        def close_lists(keep: int = 0) -> None:
            while len(lists) > keep:
                container, item = lists.pop()
                out.append(f"</{item}></{container}>")

        def list_item(markers: str, body: str) -> None:
            wanted = [_LIST_TAGS[m] for m in markers]
            common = 0
            while common < min(len(lists), len(wanted)):
                if lists[common][0] != wanted[common][0]:
                    break
                if common < len(wanted) - 1 and lists[common][1] != wanted[common][1]:
                    break
                common += 1
            close_lists(common)
            if common == len(wanted):
                out.append(f"</{lists[-1][1]}><{wanted[-1][1]}>")
                lists[-1] = wanted[-1]
            else:
                for container, item in wanted[common:]:
                    out.append(f"<{container}><{item}>")
                    lists.append((container, item))
            out.append(self.inline(body))

        while i < len(lines):
            line = lines[i]
            if not line.strip():
                flush_paragraph()
                close_lists()
                i += 1
                continue
            # Protected <pre> regions were isolated onto their own logical line.
            if line.startswith("\x00") and line.endswith("\x00") and line.count("\x00") == 2:
                kind, body = self.spans[int(line[1:-1])]
                if kind == "pre":
                    flush_paragraph()
                    close_lists()
                    out.append("<pre>" + _text(body) + "</pre>")
                    i += 1
                    continue
            if line.startswith(" "):
                flush_paragraph()
                close_lists()
                body_lines: list[str] = []
                while i < len(lines) and lines[i].startswith(" "):
                    body_lines.append(lines[i][1:])
                    i += 1
                out.append("<pre>" + self.inline("\n".join(body_lines)) + "</pre>")
                continue
            if line.startswith("{|"):
                flush_paragraph()
                close_lists()
                end, depth, nested = i + 1, 1, False
                while end < len(lines):
                    if lines[end].startswith("{|"):
                        depth += 1
                        nested = True
                    elif lines[end].strip() == "|}":
                        depth -= 1
                        if not depth:
                            end += 1
                            break
                    end += 1
                table_lines = lines[i:end]
                if depth or nested:
                    out.append("<pre>" + escape(self.source_text("\n".join(table_lines)), quote=False) + "</pre>")
                else:
                    out.append(self.table(table_lines))
                i = end
                continue
            stripped = line.rstrip()
            leading = len(stripped) - len(stripped.lstrip("="))
            trailing = len(stripped) - len(stripped.rstrip("="))
            if (1 <= leading <= 6 and leading == trailing
                    and stripped[leading:-leading].strip()):
                flush_paragraph()
                close_lists()
                body = self.inline(stripped[leading:-leading].strip())
                title = _plain_html(body)
                base = _anchor(title)
                number = self.id_counts.get(base, 1)
                anchor = base if number == 1 else f"{base}_{number}"
                while anchor in self.ids:
                    number += 1
                    anchor = f"{base}_{number}"
                self.id_counts[base] = number + 1
                self.ids.add(anchor)
                self.headings.append((leading, anchor, title))
                out.append(f'<h{leading} id="{escape(anchor, quote=True)}">{body}</h{leading}>')
                i += 1
                continue
            if stripped.startswith("----") and not stripped.strip("-"):
                flush_paragraph()
                close_lists()
                out.append("<hr>")
                i += 1
                continue
            depth = 0
            while depth < len(line) and line[depth] in _LIST_TAGS:
                depth += 1
            if 0 < depth <= self.max_list_depth:
                flush_paragraph()
                markers, body = line[:depth], line[depth:].strip()
                if markers[-1] == ";":
                    parts = _split_outside(body, ":", 1)
                    list_item(markers, parts[0].strip())
                    if len(parts) == 2:
                        list_item(markers[:-1] + ":", parts[1].strip())
                else:
                    list_item(markers, body)
                i += 1
                continue
            close_lists()
            paragraph.append(line)
            i += 1
        flush_paragraph()
        close_lists()
        return "\n".join(out)

    def toc(self) -> str:
        items = [f'<li class="toc-level-{level}"><a href="#{quote(anchor, safe="")}">'
                 f'{escape(title, quote=False)}</a></li>' for level, anchor, title in self.headings]
        return '<nav class="wiki-toc" aria-label="Contents">\n<ul>\n' + "\n".join(items) + "\n</ul>\n</nav>"



### WIKI to HTML
### ============================================================================

def HTML(
    text: str,
    *,
    wiki_base: str = "/wiki/",
    link_resolver: Callable[[str], str | None] | None = None,
    show_toc: bool = False,
    max_input_chars: int = 1_000_000,
    max_list_depth: int = 32,
) -> str:
    """Return an HTML fragment from a practical subset of MediaWiki markup.

    Supports headings, paragraphs, bold/italic, mixed/nested lists, definitions,
    horizontal rules, internal/external links, bare HTTP(S) URLs, flat tables,
    <nowiki>, <pre>, <code>, <br>, comments, and an optional table of contents.

    wiki_base: Prefix for internal page URLs; a trailing slash is added.
    link_resolver: Optional callback taking a decoded page target, including its
        fragment. Return a literal URL (not HTML), or None to leave only its label.
        Exceptions propagate. Rejected URLs also leave only the label.
    show_toc: Prepend a flat navigation list; classes record heading levels.
    max_input_chars: Reject larger input, rather than silently truncating it.
    max_list_depth: Deeper list lines are displayed as ordinary text.

    Arbitrary HTML is escaped, not executed. Only http, https, mailto, and
    relative URLs are emitted; backslashes/protocol-relative URLs are rejected.
    This is a renderer, not a complete MediaWiki engine or a general HTML
    sanitizer. Templates and File/Image/Category directives are not expanded.
    Input should be wiki source, not an HTML document. The result belongs in
    an HTML element's content, never inside an attribute, script, or style.
    All per-document state is local to the call. No I/O is performed.
    """
    if not isinstance(text, str):
        raise TypeError("text must be str")
    if not isinstance(wiki_base, str):
        raise TypeError("wiki_base must be str")
    if link_resolver is not None and not callable(link_resolver):
        raise TypeError("link_resolver must be callable or None")
    if not isinstance(show_toc, bool):
        raise TypeError("show_toc must be bool")
    for name, value in (("max_input_chars", max_input_chars), ("max_list_depth", max_list_depth)):
        if isinstance(value, bool) or not isinstance(value, int) or value < 1:
            raise ValueError(f"{name} must be a positive integer")
    if len(text) > max_input_chars:
        raise ValueError(f"input exceeds max_input_chars={max_input_chars}")
    base = _safe_url(wiki_base)
    if base is None:
        raise ValueError("wiki_base must be a safe relative path or an HTTP(S) URL")
    parts = urlsplit(base)
    if "?" in base or "#" in base or parts.scheme.lower() not in {"", "http", "https"}:
        raise ValueError("wiki_base cannot contain a query or fragment; use link_resolver instead")
    renderer = _Renderer(base.rstrip("/") + "/", link_resolver, max_list_depth)
    html = renderer.blocks(renderer.protect(text))
    if show_toc and renderer.headings:
        html = renderer.toc() + "\n" + html
    return html



class _MarkdownNode:
    def __init__(self, tag: str = "", attrs: list | None = None) -> None:
        self.tag = tag
        self.attrs = dict(attrs or [])
        self.children: list[str | _MarkdownNode] = []

    def html(self) -> str:
        attrs = "".join(f' {key}="{escape(value, quote=True)}"'
                        for key, value in self.attrs.items())
        body = "".join(escape(child, quote=False) if isinstance(child, str)
                       else child.html() for child in self.children)
        return f"<{self.tag}{attrs}>" + ("" if self.tag in {"br", "hr"}
                                        else body + f"</{self.tag}>")

    def plain(self) -> str:
        return "".join(child if isinstance(child, str) else child.plain()
                       for child in self.children)


class _MarkdownParser(HTMLParser):
    """Read only HTML produced by HTML(), not arbitrary user HTML."""
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.root = _MarkdownNode()
        self.stack = [self.root]

    def handle_starttag(self, tag: str, attrs: list) -> None:
        node = _MarkdownNode(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in {"br", "hr"}:
            self.stack.append(node)

    def handle_endtag(self, tag: str) -> None:
        self.stack.pop()

    def handle_data(self, data: str) -> None:
        self.stack[-1].children.append(data)


def _markdown_text(text: str) -> str:
    # Escape literal wiki text so it cannot introduce Markdown formatting.
    return "".join("\\" + char if char in "\\`*_[]<>~#+-=!|." else char
                   for char in text)


def _markdown_code(text: str, block: bool = False) -> str:
    longest = run = 0
    for char in text:
        run = run + 1 if char == "`" else 0
        longest = max(longest, run)
    fence = "`" * max(3 if block else 1, longest + 1)
    if block:
        return fence + "\n" + text + ("" if text.endswith("\n") else "\n") + fence + "\n\n"
    text = text.replace("\n", " ")
    padding = " " if (text.startswith("`") or text.endswith("`")
                      or (text.startswith(" ") and text.endswith(" ") and text.strip())) else ""
    return fence + padding + text + padding + fence if text else ""


def _markdown_node(node: _MarkdownNode) -> str:
    tag = node.tag
    if tag == "pre":
        return _markdown_code(node.plain(), block=True)
    if tag == "code":
        return _markdown_code(node.plain())
    if tag in {"dl", "nav"}:
        # GFM supports HTML for structures without a native Markdown equivalent.
        return node.html() + "\n\n"
    if tag in {"ul", "ol"}:
        items: list[str] = []
        for child in node.children:
            if not isinstance(child, _MarkdownNode):
                continue
            marker = "1. " if tag == "ol" else "- "
            body = _markdown_node(child).strip("\n")
            lines = body.split("\n")
            items.append(marker + lines[0] + "".join(
                "\n" + " " * len(marker) + line for line in lines[1:]))
        return "\n".join(items) + "\n\n"
    if tag == "table":
        rows = [child for child in node.children
                if isinstance(child, _MarkdownNode) and child.tag == "tr"]
        cells = [[child for child in row.children if isinstance(child, _MarkdownNode)]
                 for row in rows]
        if not cells or any("colspan" in cell.attrs or "rowspan" in cell.attrs
                            for row in cells for cell in row):
            return node.html() + "\n\n"
        width = max(map(len, cells))
        values = [[_markdown_node(cell).strip().replace("\n", "<br>")
                   .replace("\\|", "|").replace("|", "\\|")
                   for cell in row] for row in cells]
        # A headerless wiki table gets an empty GFM header, preserving its data.
        if not all(cell.tag == "th" for cell in cells[0]):
            values.insert(0, [""] * width)
        values.insert(1, ["---"] * width)
        caption = "".join(_markdown_node(child).strip() + "\n\n"
                          for child in node.children
                          if isinstance(child, _MarkdownNode) and child.tag == "caption")
        return caption + "\n".join("| " + " | ".join(row + [""] * (width - len(row)))
                                   + " |" for row in values) + "\n\n"
    if not tag:
        return "".join(_markdown_node(child) for child in node.children
                       if isinstance(child, _MarkdownNode))
    if tag == "li":
        # Nested lists must start on a new line, under their parent item.
        item = ""
        for child in node.children:
            if isinstance(child, _MarkdownNode) and child.tag in {"ul", "ol"}:
                item = item.rstrip("\n") + "\n" + _markdown_node(child)
            else:
                item += _markdown_text(child) if isinstance(child, str) else _markdown_node(child)
        return item
    body = "".join(_markdown_text(child) if isinstance(child, str)
                   else _markdown_node(child) for child in node.children)
    if tag == "p":
        return body + "\n\n"
    if tag in {"b", "i"}:
        marker = "**" if tag == "b" else "*"
        # Markdown delimiters must touch non-whitespace content.
        stripped = body.strip()
        if not stripped:
            return body
        start = len(body) - len(body.lstrip())
        end = len(body.rstrip())
        return body[:start] + marker + stripped + marker + body[end:]
    if tag == "a":
        destination = quote(node.attrs["href"], safe="/:#?&=%@+;,!$~-._")
        return f"[{body}]({destination})"
    if tag in {"h1", "h2", "h3", "h4", "h5", "h6"}:
        anchor = escape(node.attrs["id"], quote=True)
        return f'<a id="{anchor}"></a>\n\n' + "#" * int(tag[1]) + " " + body + "\n\n"
    if tag == "br":
        return "<br>"
    if tag == "hr":
        return "---\n\n"
    return body


### WIKI to GitHub Flavoured Markdown
### ============================================================================

def Markdown(
    text: str,
    *,
    wiki_base: str = "/wiki/",
    link_resolver: Callable[[str], str | None] | None = None,
    show_toc: bool = False,
    max_input_chars: int = 1_000_000,
    max_list_depth: int = 32,
) -> str:
    """Convert the same MediaWiki subset as HTML() to GitHub Flavoured Markdown.

    Options and input validation match HTML(). Supports Markdown headings,
    emphasis, links, nested lists, fenced code, horizontal rules and pipe tables.
    Explicit HTML anchors preserve wiki section links. Definition lists, a TOC,
    and tables with merged cells use safe HTML supported by GFM. Templates and
    unsupported wiki directives remain literal text; arbitrary HTML is escaped.
    No dependencies, template expansion, network requests or other I/O are used.
    """
    html = HTML(text, wiki_base=wiki_base, link_resolver=link_resolver,
                show_toc=show_toc, max_input_chars=max_input_chars,
                max_list_depth=max_list_depth)
    parser = _MarkdownParser()
    parser.feed(html)
    parser.close()
    return _markdown_node(parser.root).rstrip("\n")


### Wiki Headers
### ============================================================================

def Headers(text: str) -> list:

    if not isinstance(text,str):
        return []

    counters = [0] * 6
    headers: list[dict[str, str]] = []


    for line in text.splitlines():

        stripped = line.lstrip()

        # Markdown allows up to three leading spaces before a heading.
        leading_spaces = len(line) - len(stripped)
        if leading_spaces > 3:
            continue

        if not stripped.startswith("#"):
            continue

        level = 0

        while level < len(stripped) and stripped[level] == "#":
            level += 1

        if level == 0 or level > 6:
            continue

        # A space must follow the heading markers.
        if level >= len(stripped) or not stripped[level].isspace():
            continue

        title = stripped[level:].strip()

        if not title:
            continue

        # Remove optional closing heading markers.
        title = title.rstrip()

        while title.endswith("#"):
            title = title[:-1].rstrip()

        if not title:
            continue

        counters[level - 1] += 1

        # Reset all child heading counters.
        for index in range(level, len(counters)):
            counters[index] = 0

        id_depth = max(3, level)
        section_id = ".".join(
            str(value) for value in counters[:id_depth]
        )

        headers.append({
            "id": section_id,
            "title": title,
        })

    return headers
